#!/usr/bin/env node
/**
 * Writes app/utils/versification/tables.ts from the bibletags-versification data (MIT, Gospel Paths
 * Corporation): the original's verse counts and the tables that place every verse of the original
 * (Hebrew and Greek) in the Synodal and in the King James numbering.
 *
 * Usage: node scripts/build-versification.mjs <bibletags-versification/src/data> [commit]
 *
 * The source files are JavaScript; they are read as data — comments and the module wrapper are
 * stripped and the rest parsed as JSON — and never run. The output is committed; the source is
 * not. See app/utils/versification/THIRD_PARTY_NOTICES.md for the licence.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const asData = (file) => {
  const text = readFileSync(file, 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/[^\n]*/g, '')
    .replace(/export default \w+/, '')
    .replace(/const \w+ =/, '')
    .trim()
    .replace(/,(\s*[}\]])/g, '$1');
  return JSON.parse(text);
};

const main = () => {
  const [dataDir, commit = 'unknown'] = process.argv.slice(2);
  if (!dataDir) {
    console.error('Usage: node scripts/build-versification.mjs <bibletags-versification/src/data> [commit]');
    process.exit(1);
  }
  const counts = asData(join(dataDir, 'numberOfVersesPerChapterPerBook.js'));
  const synodal = asData(join(dataDir, 'synodalVerseMappings.js'));
  const kjvLike = asData(join(dataDir, 'kjvLikeVerseMappings.js'));
  if (counts.length !== 66) throw new Error(`expected 66 books, got ${counts.length}`);
  const out = `// GENERATED by scripts/build-versification.mjs — do not edit by hand.
// Source: github.com/educational-resources-and-services/bibletags-versification, commit ${commit},
// src/data. MIT licence, Copyright (c) 2022 Gospel Paths Corporation (THIRD_PARTY_NOTICES.md).
//
// Locations are BBCCCVVV: the book in King James order (1–66), the chapter, the verse. A key is one
// verse of the original, a verse range ("…-VVV") moved by a number, or part of a verse (":W1-W2",
// by word); a value is where it stands in the numbering, or the number to add to a range.

/** Verses per chapter of the original (Hebrew Bible and Greek New Testament), book by book. */
export const ORIGINAL_VERSE_COUNTS: readonly (readonly number[])[] = ${JSON.stringify(counts)};

export type NumberingRule = string | number;

/** The original placed in the Synodal numbering. */
export const SYNODAL_TABLE: Readonly<Record<string, NumberingRule>> = ${JSON.stringify(synodal, null, 1)};

/** The original placed in the King James numbering. */
export const KJV_TABLE: Readonly<Record<string, NumberingRule>> = ${JSON.stringify(kjvLike, null, 1)};
`;
  const target = resolve('app/utils/versification/tables.ts');
  writeFileSync(target, out);
  console.log(`wrote ${target}: ${Object.keys(synodal).length} Synodal rules, ${Object.keys(kjvLike).length} King James rules`);
};

main();
